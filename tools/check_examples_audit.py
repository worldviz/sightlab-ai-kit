#!/usr/bin/env python3
"""Run check.py over every shipped example script and tally the findings (Task 4, step 6).

Writes a Markdown audit: counts per code, the share of examples each code touches, and the
scripts with the most findings. A code that flags more than a quarter of the examples is
either a false positive to fix or a real pattern to document.

Usage: check_examples_audit.py [--sources DIR] [--out docs/audits/<date>-check-over-examples.md]
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path

KIT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(KIT / "src" / "harness"))
from check import check_script, load_api  # noqa: E402

DEFAULT_SOURCES = Path.home() / "development" / "sightlab-2x-sources"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--sources", type=Path, default=DEFAULT_SOURCES)
    p.add_argument("--out", type=Path, default=KIT / "docs" / "audits" / f"{date.today().isoformat()}-check-over-examples.md")
    a = p.parse_args(argv)

    api = load_api(KIT / "src" / "api" / "sightlab-api.json")
    resources = {l.strip() for l in (a.sources / "resources-list.txt").read_text().splitlines() if l.strip()}
    index = json.loads((KIT / "src" / "examples" / "index.json").read_text())

    per_code = Counter()
    examples_with_code: dict[str, set] = defaultdict(set)
    per_script: list[tuple[int, str, list[str]]] = []
    scripts_checked = 0
    scripts_with_instance = 0
    for e in index:
        for s in e["scripts"]:
            path = a.sources / "ExampleScripts" / e["folder"] / s
            if not path.is_file():
                continue
            r = check_script(path, api, resources)
            scripts_checked += 1
            if r["instances"]:
                scripts_with_instance += 1
            codes = [f["code"] for f in r["errors"] + r["warnings"]]
            for c in set(codes):
                per_code[c] += 1
                examples_with_code[c].add(e["folder"])
            if codes:
                per_script.append((len(codes), f"{e['folder']}/{s}", codes))
    per_script.sort(reverse=True)

    n_ex = len(index)
    lines = [
        "---", f"created: {date.today().isoformat()}", "author: Claude (Fable 5.1), generated by tools/check_examples_audit.py", "---", "",
        f"# check.py over the shipped examples ({date.today().isoformat()})", "",
        f"{scripts_checked} scripts in {n_ex} example folders; {scripts_with_instance} create a SightLab instance "
        "(the rest are replay, config or helper modules and get no frame checks).", "",
        "| Code | Scripts | Example folders | Share of folders |", "| --- | --- | --- | --- |",
    ]
    for code, n in per_code.most_common():
        k = len(examples_with_code[code])
        flag = " **(>25 %)**" if k > n_ex / 4 else ""
        lines.append(f"| `{code}` | {n} | {k} | {100 * k / n_ex:.0f} %{flag} |")
    lines += ["", "## Scripts with the most findings", ""]
    for n, name, codes in per_script[:10]:
        lines.append(f"- `{name}`: {', '.join(sorted(set(codes)))}")
    lines += [
        "", "## Reading the table", "",
        "- `W_NO_GAZE_OBJECT` fires on every `gui=False` script that registers no gaze object. Many shipped",
        "  examples are legitimately not gaze studies (agents, collision, toggles, screen-based tasks), so a",
        "  high share here is expected. The warning stays because it is exactly the mistake to catch in an",
        "  agent-built study whose brief asks for gaze data; `SKILL.md` tells the agent to answer it from the",
        "  brief, not to silence it.",
        "- `W_VIZ_GO` and `W_UNPAIRED_TRIAL` on shipped examples are real observations about those scripts",
        "  (older examples call `viz.go()`; some start and end trials from different functions).",
        "- `E_NO_RUN_EXPERIMENT` on shipped examples marks helper modules that construct a SightLab object but",
        "  are driven from another file; the agent-built frame always schedules it.",
        "",
    ]
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[6:]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
